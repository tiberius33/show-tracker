#!/usr/bin/env node
/**
 * Regenerates netlify/functions/lib/contentFilterRule.js from
 * lib/contentFilter.js.
 *
 * The content filter has to run in two places: in the browser, so a user
 * gets an inline error instead of a rejected write, and in a Netlify
 * function, so the check cannot be skipped by writing to Firestore
 * directly. Functions are CommonJS and cannot require the app's ESM
 * modules, which is why netlify/functions/lib/festivalMatchRule.js exists
 * in the same shape.
 *
 * The festival rule is maintained as a hand-kept copy guarded by a parity
 * test. This one is generated instead, because a wordlist is going to be
 * edited far more often than a date-window rule, and every hand edit is a
 * chance for the two copies to disagree about what is publishable —
 * exactly the drift that let a mistyped-year bound go missing from one
 * copy of the festival rule (see the v5.31.0 notes).
 *
 * Run after editing lib/contentFilter.js:
 *   node scripts/generate-content-filter-rule.js
 *
 * lib/__tests__/contentFilterParity.test.js fails if the generated file is
 * stale, so CI catches a forgotten run.
 */

const fs = require('fs');
const path = require('path');

const ROOT = path.join(__dirname, '..');
const SOURCE = path.join(ROOT, 'lib', 'contentFilter.js');
const TARGET = path.join(ROOT, 'netlify', 'functions', 'lib', 'contentFilterRule.js');

const HEADER = `/**
 * contentFilterRule — the CommonJS half of lib/contentFilter.js, so a
 * Netlify function can apply exactly the filter the client applies.
 *
 * WHY A COPY RATHER THAN AN IMPORT. Same reason
 * netlify/functions/lib/festivalMatchRule.js exists: functions are
 * CommonJS and cannot require the app's ESM modules, and the alternative
 * — every function re-implementing the rule inline — is what let the
 * festival match rule drift until a bound that stopped a mistyped year
 * had to be applied by hand to each copy (see v5.31.0).
 *
 * WHY THAT IS SAFE HERE. This file is GENERATED from lib/contentFilter.js
 * by scripts/generate-content-filter-rule.js, and
 * lib/__tests__/contentFilterParity.test.js runs both copies over the same
 * inputs and asserts identical answers. Edit lib/contentFilter.js and
 * re-run the generator; do not edit this file by hand.
 */

`;

function generate(source) {
  // Everything from the wordlist down — the block comment at the top of
  // the ESM file is replaced by HEADER, which says the right thing for a
  // generated file.
  const start = source.indexOf('// ── The wordlist');
  if (start === -1) {
    throw new Error('lib/contentFilter.js no longer starts its body with the wordlist banner');
  }

  const body = source.slice(start).replace(/^export (const|function) /gm, '$1 ');

  const exported = [...source.matchAll(/^export (?:const|function) (\w+)/gm)].map((m) => m[1]);
  if (exported.length === 0) {
    throw new Error('lib/contentFilter.js exports nothing — refusing to generate an empty module');
  }

  const footer = `\nmodule.exports = {\n${exported.map((name) => `  ${name},\n`).join('')}};\n`;
  return HEADER + body + footer;
}

const generated = generate(fs.readFileSync(SOURCE, 'utf8'));

// `--check` is what the parity test uses: exit non-zero if the checked-in
// file is not what the generator would write right now.
if (process.argv.includes('--check')) {
  const current = fs.existsSync(TARGET) ? fs.readFileSync(TARGET, 'utf8') : '';
  if (current !== generated) {
    console.error('netlify/functions/lib/contentFilterRule.js is stale.');
    console.error('Run: node scripts/generate-content-filter-rule.js');
    process.exit(1);
  }
  console.log('contentFilterRule.js is up to date.');
  process.exit(0);
}

fs.writeFileSync(TARGET, generated);
console.log(`Wrote ${path.relative(ROOT, TARGET)}`);

module.exports = { generate };
